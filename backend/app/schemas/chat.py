from pydantic import BaseModel, Field
from typing import Optional, List
from datetime import datetime

class CitationSnippet(BaseModel):
    section_number: Optional[str] = Field(default=None, description="Section or article number")
    section_title: Optional[str] = Field(default=None, description="Section header name")
    page_number: Optional[int] = Field(default=1, description="Page number where the text originates")
    verbatim_quote: str = Field(description="Exact snippet or excerpt from the contract used to support the answer")
    relevance_score: Optional[float] = Field(default=None, description="Similarity or retrieval score")

class ChatRequest(BaseModel):
    contract_id: str
    message: str = Field(description="User question about the contract")
    include_citations: bool = Field(default=True, description="Whether to include grounded clause citations")

class ChatResponse(BaseModel):
    contract_id: str
    reply: str = Field(description="Grounded, context-aware answer generated by the legal RAG engine")
    citations: List[CitationSnippet] = Field(default_factory=list, description="Ground-truth contract citations")
    created_at: datetime = Field(default_factory=datetime.utcnow)

class ChatHistoryItem(BaseModel):
    id: int
    role: str
    message: str
    citations: Optional[List[CitationSnippet]] = []
    created_at: datetime

    class Config:
        from_attributes = True
